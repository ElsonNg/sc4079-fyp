"""Ollama-backed code transformer for the Tier-2 LLM-transformed evaluation set.

Mirrors the request/response pattern of ``review_explanation.py`` (structured
``/api/chat`` output, model-availability check, retry-twice) but drives a
*different* model than the reviewer (gemma4:e4b vs. qwen3:8b), so the benchmark is
never generated by the same model that scores/explains it.

Every output is fed through ``candidate_gate.diagnostic_preservation_gate`` by the
caller; this module only produces candidate rewrites, it does not judge them.
"""

from __future__ import annotations

import json
from dataclasses import dataclass
from urllib.parse import urljoin, urlparse

import requests

DEFAULT_OLLAMA_HOST = "http://127.0.0.1:11434"
DEFAULT_TRANSFORM_MODEL = "gemma4:e4b"
DEFAULT_TRANSFORM_TIMEOUT = 180.0

CloneType = str  # "type_3" | "type_4"
Side = str  # "vulnerable" | "patched"

_CODE_SCHEMA = {
    "type": "object",
    "properties": {"code": {"type": "string"}},
    "required": ["code"],
}

_SYSTEM_PROMPT = (
    "You are a code-transformation tool that builds a software-clone-detection "
    "benchmark. You rewrite a single JavaScript or TypeScript function. You MUST "
    "preserve the function's exact runtime behaviour. You MUST NOT fix bugs, add "
    "input validation, add sanitisation, change security-relevant logic, remove or "
    "rename calls to library APIs, or change what the function computes. Return only "
    "the rewritten function body/source via the structured schema, with no commentary."
)

_TYPE3_INSTRUCTION = (
    "Rewrite the function below as a NEAR-DUPLICATE (Type-3 clone). Keep the overall "
    "structure recognisable, but apply surface changes: rename local variables and "
    "parameters, reorder independent statements, change formatting, and optionally "
    "insert an inert dead branch or split a return into a temporary variable. Do not "
    "change behaviour."
)

_TYPE4_INSTRUCTION = (
    "Rewrite the function below as a SEMANTIC CLONE (Type-4 clone). Reimplement it "
    "with different control-flow constructs and different idioms while preserving "
    "exactly the same behaviour. You may replace loops with equivalent constructs, "
    "restructure conditionals, and change variable organisation, but you MUST keep "
    "every call to a library or security-relevant API and every literal constant "
    "(strings, regexes, numbers) unchanged."
)

_PATCHED_NOTE = (
    " This is PATCHED (already-fixed) code: preserve the fix exactly and do NOT "
    "reintroduce the original vulnerability."
)


class LlmTransformError(RuntimeError):
    def __init__(self, reason_code: str, detail: str = "") -> None:
        self.reason_code = reason_code
        self.detail = detail
        super().__init__(f"{reason_code}: {detail}" if detail else reason_code)


@dataclass(frozen=True)
class TransformConfig:
    model: str = DEFAULT_TRANSFORM_MODEL
    host: str = DEFAULT_OLLAMA_HOST
    timeout: float = DEFAULT_TRANSFORM_TIMEOUT
    temperature: float = 0.5


def _endpoint(host: str, path: str) -> str:
    parsed = urlparse(host if "://" in host else f"http://{host}")
    base = f"{parsed.scheme}://{parsed.netloc}"
    return urljoin(base + "/", path.lstrip("/"))


def _build_prompt(source: str, clone_type: CloneType, side: Side, language: str) -> str:
    instruction = _TYPE3_INSTRUCTION if clone_type == "type_3" else _TYPE4_INSTRUCTION
    note = _PATCHED_NOTE if side == "patched" else ""
    return (
        f"{instruction}{note}\n\n"
        f"Language: {language}\n"
        f"Function source:\n```\n{source}\n```"
    )


class OllamaCodeTransformer:
    def __init__(
        self,
        config: TransformConfig | None = None,
        *,
        session: requests.Session | None = None,
    ) -> None:
        self.config = config or TransformConfig()
        self.session = session or requests.Session()

    def ensure_model_available(self) -> None:
        try:
            response = self.session.get(_endpoint(self.config.host, "/api/tags"), timeout=self.config.timeout)
            response.raise_for_status()
        except requests.RequestException as exc:
            raise LlmTransformError("ollama_unavailable", str(exc)) from exc
        names = {
            entry.get("name") or entry.get("model")
            for entry in response.json().get("models", [])
        }
        if self.config.model not in names:
            raise LlmTransformError("model_missing", f"{self.config.model} not in {sorted(n for n in names if n)}")

    def transform(
        self,
        source: str,
        *,
        clone_type: CloneType,
        side: Side,
        language: str = "javascript",
        temperature: float | None = None,
    ) -> str:
        prompt = _build_prompt(source, clone_type, side, language)
        request_body = {
            "model": self.config.model,
            "messages": [
                {"role": "system", "content": _SYSTEM_PROMPT},
                {"role": "user", "content": prompt},
            ],
            "stream": False,
            "think": False,
            "format": _CODE_SCHEMA,
            "keep_alive": "10m",
            "options": {
                "temperature": self.config.temperature if temperature is None else temperature
            },
        }
        last_error: Exception | None = None
        for _attempt in range(2):
            try:
                response = self.session.post(
                    _endpoint(self.config.host, "/api/chat"),
                    json=request_body,
                    timeout=self.config.timeout,
                )
                if response.status_code == 404:
                    raise LlmTransformError("model_missing", response.text)
                response.raise_for_status()
                content = response.json()["message"]["content"]
                return _extract_code(content)
            except LlmTransformError:
                raise
            except requests.Timeout as exc:
                last_error = LlmTransformError("timeout", str(exc))
            except (requests.RequestException, KeyError, ValueError) as exc:
                last_error = LlmTransformError("invalid_response", str(exc))
        raise last_error or LlmTransformError("invalid_response", "unknown")


def _extract_code(content: str) -> str:
    """Pull the ``code`` field out of a structured response, tolerating a model
    that returns bare code or a fenced block despite the schema."""
    text = content.strip()
    try:
        parsed = json.loads(text)
        if isinstance(parsed, dict) and isinstance(parsed.get("code"), str):
            text = parsed["code"]
    except json.JSONDecodeError:
        pass
    if text.startswith("```"):
        lines = text.splitlines()
        if lines and lines[0].startswith("```"):
            lines = lines[1:]
        if lines and lines[-1].strip() == "```":
            lines = lines[:-1]
        text = "\n".join(lines)
    return text.strip()
